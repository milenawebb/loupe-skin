import { PDF_PAGE, PDF_THEME, exportTitle, exportTimestamp, type ExportSheet } from "@/lib/sheet-export";
import { pickedFrames, picksFilename, picksGrid } from "@/lib/sheet-picks";
import { framePageUrl } from "@/lib/export-config";
import { tileSeekTime } from "@/lib/sheet-seek";

async function readableImage(url: string) {
  const image = new Image();
  image.crossOrigin = "anonymous";
  await new Promise<void>((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error("Image timed out")), 12000);
    image.onload = () => { clearTimeout(timeout); resolve(); };
    image.onerror = () => { clearTimeout(timeout); reject(new Error("Image unavailable")); };
    image.src = url;
  });
  const test = document.createElement("canvas");
  test.width = test.height = 1;
  const context = test.getContext("2d");
  if (!context) throw new Error("Canvas unavailable");
  context.drawImage(image, 0, 0, 1, 1);
  context.getImageData(0, 0, 1, 1);
  return image;
}

export async function savePicksPdf(sheet: ExportSheet, picks: ReadonlySet<number>, videoTitle: string, pageUrl: string, playbackId: string) {
  const frames = pickedFrames(sheet, picks);
  if (!frames.length) return;
  const grid = picksGrid(sheet.tile_width / sheet.tile_height, frames.length);
  const [sprite, logo] = await Promise.all([readableImage(sheet.url), readableImage("/loupe-logo.png")]);
  await document.fonts.load('12px "JetBrains Mono"');
  const images = await Promise.all(frames.map(async tile => {
    try { return await readableImage(`https://image.mux.com/${playbackId}/thumbnail.jpg?time=${tile.start}&width=${grid.thumbnailWidth}`); }
    catch { return null; }
  }));
  const wordmark = document.createElement("canvas"); wordmark.width = 1086; wordmark.height = 412;
  const mark = wordmark.getContext("2d");
  if (!mark) throw new Error("Canvas unavailable");
  mark.drawImage(logo, 29, 69, 1086, 412, 0, 0, 1086, 412);
  mark.globalCompositeOperation = "source-in"; mark.fillStyle = PDF_THEME.text; mark.fillRect(0, 0, 1086, 412);
  const { jsPDF } = await import("jspdf");
  const pdf = new jsPDF({ orientation: "portrait", unit: "pt", format: "letter", compress: true });
  const title = `${exportTitle(videoTitle, playbackId)} · Picks`;
  pdf.setProperties({ title, subject: "Loupe selected frames", creator: "Loupe" });
  pdf.viewerPreferences({ DisplayDocTitle: true });
  for (let offset = 0; offset < frames.length; offset += grid.perPage) {
    if (offset) pdf.addPage();
    const canvas = document.createElement("canvas"); canvas.width = PDF_PAGE.width * 3; canvas.height = PDF_PAGE.height * 3;
    const ctx = canvas.getContext("2d"); if (!ctx) throw new Error("Canvas unavailable");
    ctx.scale(3, 3); ctx.fillStyle = PDF_THEME.background; ctx.fillRect(0, 0, 612, 792);
    ctx.drawImage(wordmark, 36, 34, 90, 90 * 412 / 1086);
    ctx.fillStyle = PDF_THEME.text; ctx.font = '12px "JetBrains Mono", monospace'; ctx.fillText(title, 140, 49, 436);
    ctx.fillStyle = PDF_THEME.dim; ctx.font = '8px "JetBrains Mono", monospace';
    ctx.fillText(`${exportTimestamp(sheet.duration, sheet.duration)}  ·  ${frames.length} frames  ·  ${new Date().toISOString().slice(0, 10)}`, 140, 66, 436);
    const links = frames.slice(offset, offset + grid.perPage).map((tile, i) => {
      const x = 36 + i % grid.columns * (grid.imageWidth + 10);
      const y = 86 + Math.floor(i / grid.columns) * (grid.cellHeight + 10);
      const image = images[offset + i];
      if (image) ctx.drawImage(image, x, y, grid.imageWidth, grid.imageHeight);
      else ctx.drawImage(sprite, tile.x, tile.y, sheet.tile_width, sheet.tile_height, x, y, grid.imageWidth, grid.imageHeight);
      ctx.fillStyle = PDF_THEME.dim; ctx.font = '8px "JetBrains Mono", monospace'; ctx.textAlign = "left";
      ctx.fillText(String(tile.index + 1).padStart(2, "0"), x, y + grid.imageHeight + 11);
      ctx.textAlign = "right"; ctx.fillText(exportTimestamp(tile.start, sheet.duration), x + grid.imageWidth, y + grid.imageHeight + 11);
      return { x, y, time: tileSeekTime(sheet.tiles, tile.index, sheet.duration) };
    });
    ctx.textAlign = "left"; ctx.font = '7px "JetBrains Mono", monospace'; ctx.fillText(pageUrl, 36, 755, 420);
    ctx.textAlign = "right"; ctx.fillText("Generated by Loupe", 576, 755);
    pdf.addImage(canvas.toDataURL("image/png"), "PNG", 0, 0, 612, 792);
    for (const link of links) pdf.link(link.x, link.y, grid.imageWidth, grid.cellHeight, { url: framePageUrl(pageUrl, link.time) });
    pdf.link(36, 746, 420, 12, { url: pageUrl });
  }
  pdf.save(picksFilename(videoTitle, playbackId));
}